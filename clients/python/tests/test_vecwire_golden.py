"""Byte-for-byte differential test of the Python vector encoders vs the Go
reference.

The vector op arg layouts — especially create_collection's config trailer, with
its forced-presence chain — are fragile: a single field-order or type slip
produces a malformed request the server may accept and misinterpret. So rather
than trust a reading of the Go encoder, this asserts the Python output is
byte-identical to what Go's ops.Encode*Args produced, for a matrix of configs.

The golden fixtures live in _oracle/golden.txt, generated by _oracle/main.go:

    go run ./clients/python/tests/_oracle > clients/python/tests/_oracle/golden.txt

Regenerate them whenever an encoder changes; a drift here means the Python
client and the Go server have stopped agreeing on the wire.

Only the fixed-binary ops are byte-checked. Ops whose tail is embedded JSON
(metadata, filter, content) are covered by the cross-stack round-trip instead,
because the server unmarshals that JSON and any equivalent encoding decodes the
same — byte-identity there would over-constrain to Go's exact key order.
"""

