class VecwireGoldenTest(unittest.TestCase):
    def setUp(self):
        self.golden = _load()

    def test_create_collection_matches_go(self):
        for name, (col, cfg) in _CREATE.items():
            with self.subTest(name=name):
                got = w.encode_create_collection_args(col, cfg).hex()
                self.assertEqual(got, self.golden[name], f"{name} diverged from the Go encoder")

    def test_dataplane_binary_matches_go(self):
        for name, fn in _DATAPLANE.items():
            with self.subTest(name=name):
                self.assertEqual(fn().hex(), self.golden[name], f"{name} diverged from the Go encoder")

    def test_metadata_prefix_matches_and_json_equivalent(self):
        # insert/ttl_meta: the binary prefix must match Go exactly; the metadata
        # JSON tail need only decode to the same object.
        import json
        want = bytes.fromhex(self.golden["insert/ttl_meta"])
        got = w.encode_insert_args("docs", 7, _VEC, ttl_ms=300000,
                                   metadata={"tenant": "acme", "year": 2020})
        head = 1 + (1 + len("docs")) + 8 + 4 + 4 * len(_VEC) + 8  # flags+col+id+dim+vec+ttl
        self.assertEqual(got[:head], want[:head], "insert binary prefix diverged")
        self.assertEqual(json.loads(got[head + 4:]), json.loads(want[head + 4:]),
                         "metadata JSON is not equivalent to Go's")


class VecwireGuardTest(unittest.TestCase):
    def test_reserved_content_key_rejected(self):
        # $content is how upsert folds the content string into the metadata JSON;
        # letting a caller set it would silently override (or forge) content.
        with self.assertRaises(ValueError):
            w.encode_upsert_args("docs", 1, _VEC, content="hi",
                                 metadata={"$content": "sneaky"})
        with self.assertRaises(ValueError):
            w.encode_insert_args("docs", 1, _VEC, metadata={"$content": "sneaky"})

    def test_sparse_length_mismatch_rejected(self):
        # Unequal indices/values would write a count for the longer list but
        # zip only the shorter — a malformed, truncated binary payload.
        with self.assertRaises(ValueError):
            w.encode_insert_args("docs", 1, _VEC,
                                 sparse={"indices": [1, 2, 3], "values": [0.5, 0.5]})


class VecwireUpsertBatchTest(unittest.TestCase):
    # There is no native-TCP batch-upsert wire op (see _vecwire.encode_upsert_batch_args'
    # docstring), so this isn't a golden test — it just asserts the batch helper is
    # exactly N sequential encode_upsert_args() calls, byte for byte.
    def test_batch_equals_sequential_singles(self):
        points = [
            {"id": 1, "vector": _VEC, "content": "hello"},
            {"id": 2, "vector": _VEC, "content": "world", "metadata": {"tenant": "acme"}},
            {"id": 3, "vector": _VEC, "ttl_ms": 5000,
             "sparse": {"indices": [3, 17], "values": [0.8, 0.4]}},
        ]
        got = w.encode_upsert_batch_args("docs", points)
        want = [
            w.encode_upsert_args("docs", 1, _VEC, content="hello"),
            w.encode_upsert_args("docs", 2, _VEC, content="world", metadata={"tenant": "acme"}),
            w.encode_upsert_args("docs", 3, _VEC, ttl_ms=5000,
                                 sparse={"indices": [3, 17], "values": [0.8, 0.4]}),
        ]
        self.assertEqual(got, want)


