// This file re-exports the ops/wire leaf's client-safe wire-codec surface under
// their original ops.* names, so every existing server-side call site (cluster,
// httpapi, the root rostam package, wasm/, tests, ...) keeps compiling unchanged
// after the Encode*/Decode*/routing-key/WASM-marker functions moved to the leaf.
// The client and the golden oracle import ops/wire directly instead of going
// through these aliases, which is what lets the client stop depending on ops
// (and therefore on cache/objstore/vector-analysis).
//
// Topology/TopologyMember/EncodeTopology/DecodeTopology and the
// OpKind/KeyExtractor/KeyExtractorInto/RouteLayout family are aliased next to
// their ops-side callers (topology.go, registry.go) instead of here.

